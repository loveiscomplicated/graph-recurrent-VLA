"""Existing local identities, immutable outputs and checkpoint I/O."""
import csv
import hashlib
import json
import os
from pathlib import Path
from datetime import datetime, timezone
import numpy as np
import torch
from vla.action_codec import digest


def sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda: f.read(4 << 20), b''):
            h.update(block)
    return h.hexdigest()


def now():
    return datetime.now(timezone.utc).isoformat()


def write(path, value, *, immutable=False):
    path = Path(path); path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name+'.partial')
    with tmp.open('w') as f:
        json.dump(value, f, indent=2, allow_nan=False); f.flush(); os.fsync(f.fileno())
    if immutable:
        os.link(tmp, path); tmp.unlink()
    else:
        os.replace(tmp, path)


def read(path):
    return json.loads(Path(path).read_text())


def append_csv(path, row):
    path = Path(path); path.parent.mkdir(parents=True, exist_ok=True)
    exists = path.exists()
    with path.open('a', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(row))
        if not exists: w.writeheader()
        w.writerow(row); f.flush()


def npz(path, arrays):
    path = Path(path); path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name+'.partial')
    with tmp.open('xb') as f:
        np.savez_compressed(f, **arrays); f.flush(); os.fsync(f.fileno())
    with np.load(tmp, allow_pickle=False) as z:
        if set(z.files) != set(arrays): raise ValueError('NPZ keys differ on readback')
        for k, a in arrays.items():
            b = z[k]
            if b.dtype != np.asarray(a).dtype or b.shape != np.shape(a) or b.tobytes() != np.asarray(a).tobytes():
                raise ValueError('NPZ readback: '+k)
    os.link(tmp, path); tmp.unlink()


def tree_identity(root, *, exclude_bc=False):
    root = Path(root)
    return {str(p.relative_to(root)):sha(p) for p in sorted(root.rglob('*'))
            if p.is_file() and p.suffix in ('.py', '.json', '.toml')
            and '__pycache__' not in p.parts
            and not (exclude_bc and p.is_relative_to(root/'graph/plan_a_bc'))}


def tensor_identity(state):
    h = hashlib.sha256()
    for k, v in sorted(state.items()):
        a = v.detach().cpu().contiguous().numpy()
        h.update(k.encode()); h.update(str(a.dtype).encode()); h.update(str(a.shape).encode()); h.update(a.tobytes())
    return h.hexdigest()


def checkpoint_load(path):
    # Only files generated by this experiment or explicitly audited local inputs.
    return torch.load(path, map_location='cpu', weights_only=False)
